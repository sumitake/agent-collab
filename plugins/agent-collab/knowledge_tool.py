_ISO_TS_RE = re.compile(
    r"^\d{4}-\d{2}-\d{2}"
    r"(?:[T ]\d{2}:\d{2}(?::\d{2}(?:\.\d{1,6})?)?(?:Z|[+-]\d{2}:\d{2})?)?$"
)


def _valid_iso_timestamp(value: str) -> bool:
    """Pinned grammar THEN calendar validity: fromisoformat alone accepts
    non-ISO variants (compact dates, week dates), so the shape is
    regex-gated first."""
    candidate = value
    if candidate.endswith("Z") and "T" in candidate:
        candidate = candidate[:-1] + "+00:00"
    if not _ISO_TS_RE.match(value):
        return False
    try:
        datetime.fromisoformat(candidate)
    except ValueError:
        return False
    return True


def _refuse_symlink_components(base: Path, path: Path) -> None:
    """Every component from base down to path must be symlink-free.

    Parent-only checks are insufficient: a symlinked intermediate directory
    resolves 'inside' while the entry redirects outside.
    """
    cur = base
    for part in path.relative_to(base).parts:
        cur = cur / part
        if cur.is_symlink():
            raise SystemExit(f"refusing symlinked path component: {cur}")


def _safe_create_exclusive(base: Path, path: Path):
    """Atomically create a NEW file under base; refuse symlinks and races.

    O_CREAT|O_EXCL (|O_NOFOLLOW where available) makes create-or-fail
    atomic, closing the exists()-then-open TOCTOU window.
    """
    if not str(path.resolve().parent).startswith(str(base.resolve())):
        raise SystemExit(f"refusing output outside {base}: {path}")
    _refuse_symlink_components(base, path)
    # Anchor creation to a dir-fd of the VERIFIED parent so a concurrent
    # swap of the directory for a symlink after the component check cannot
    # redirect the write.
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    dfd = os.open(path.parent, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | nofollow)
    try:
        fd = os.open(path.name, os.O_CREAT | os.O_EXCL | os.O_WRONLY | nofollow,
                     0o600, dir_fd=dfd)
    except FileExistsError:
        raise SystemExit(f"refusing to overwrite existing file: {path}")
    finally:
        os.close(dfd)
    return os.fdopen(fd, "w", encoding="utf-8")


def _safe_output_path(root: Path, filename: str) -> Path:
    """Refuse to write through symlinks or outside root.

    The tool's contract is exactly two overwriting write paths inside the
    knowledge root; a committed symlink at either path must not redirect
    the write to an arbitrary file.
    """
    path = root / filename
    if path.is_symlink():
        raise SystemExit(f"index: refusing to write through symlink: {path}")
    if path.parent.resolve() != root.resolve():
        raise SystemExit(f"index: output path escapes root: {path}")
    return path


def generate_index(root: Path, registry: dict, log_timestamp: str | None = None) -> str:
    pages, violations = _iter_pages(root)
    if violations:
        raise SystemExit("index: refusing to generate: " + "; ".join(violations))
    index_path = _safe_output_path(root, "index.md")
    log_path = _safe_output_path(root, "log.md")
    rows = []
    for page in pages:
        text, read_violations = _read_page(page, page.name)
        if text is None:
            raise SystemExit(
                "index: refusing to generate: " + "; ".join(read_violations)
            )
        fm, _body, _v = _split_frontmatter(text, page.name)
        fm = fm or {}
        rel = page.resolve().relative_to((root / "pages").resolve()).as_posix()
        srcs = fm.get("source_ids")
        rows.append(
            "| [{title}](pages/{name}) | {status} | {kind} | {nsrc} | {reviewed} |".format(
                title=_sanitize_cell(fm.get("title", page.stem)),
                # URL-encode the path so exotic filenames cannot break or
                # reshape the generated link.
                name=quote(rel, safe="/"),
                status=_sanitize_cell(fm.get("status", "?")),
                kind=_sanitize_cell(fm.get("kind", "?")),
                # Malformed frontmatter must not crash the catalog; lint is
                # the enforcement gate, index is a resilient view.
                nsrc=len(srcs) if isinstance(srcs, list) else 0,
                reviewed=_sanitize_cell(fm.get("last_reviewed", "-")),
            )
        )
    index_text = (
        "# Knowledge index\n\n"
        "> Generated by `knowledge_tool.py index` — do not hand-edit.\n"
        "> Derived artifact; never authoritative.\n\n"
        f"Pages: {len(rows)} | Registered sources: {len(registry)}\n\n"
        "| Page | Status | Kind | Sources | Last reviewed |\n"
        "|---|---|---|---|---|\n" + ("\n".join(rows) + "\n" if rows else "")
    )
    index_path.write_text(index_text, encoding="utf-8")
    stamp = log_timestamp or _utc_now()
    prefix = "" if log_path.exists() and log_path.read_text(encoding="utf-8") else (
        "# Knowledge log\n\n"
        "> Append-only operation log, written only by "
        "`knowledge_tool.py index`.\n\n"
    )
    with log_path.open("a", encoding="utf-8") as fh:
        fh.write(
            f"{prefix}- {_sanitize_cell(stamp)} | index | "
            f"pages={len(rows)} sources={len(registry)}\n"
        )
    return index_text


