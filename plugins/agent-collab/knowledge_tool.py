_SLUG_MAX_LEN = 60
_PROPOSAL_BANNER = (
    "<!-- UNTRUSTED PROPOSAL: draft skeleton, NOT compiled knowledge. Not\n"
    "     part of the query corpus; never listed in the index; promotion is\n"
    "     a move into knowledge/pages/ plus a clean lint, through your own\n"
    "     review process. -->"
)


def _slugify(title: str) -> str:
    """Pinned slug grammar: fold -> lower -> [a-z0-9-] -> collapse/strip.

    Deterministic and separator-free by construction; empty results are
    errors, length is capped.
    """
    folded = _fold(title).lower()
    slug = re.sub(r"-+", "-", re.sub(r"[^a-z0-9]", "-", folded)).strip("-")
    slug = slug[:_SLUG_MAX_LEN].rstrip("-")
    if not slug:
        raise SystemExit(f"draft: title produces an empty slug: {title!r}")
    return slug


def create_draft(root: Path, title: str, source_ids: list[str], kind: str,
                 registry: dict) -> Path:
    """Emit a proposal skeleton to knowledge/proposals/<slug>.md.

    Forced frontmatter (status draft, trust derived_review_required) and a
    leading UNTRUSTED banner are tool-enforced on every write; you review
    and promote manually. No auto-apply, no writes to pages/.
    """
    for sid in source_ids:
        if sid not in registry:
            raise SystemExit(f"draft: unregistered source_id: {sid}")
    if kind not in PAGE_KINDS:
        raise SystemExit(f"draft: kind not in {sorted(PAGE_KINDS)}")
    proposals = root / "proposals"
    if proposals.is_symlink():
        raise SystemExit(f"draft: proposals dir is a symlink: {proposals}")
    if proposals.exists() and not proposals.is_dir():
        raise SystemExit(
            f"draft: proposals path exists but is not a directory: {proposals}"
        )
    proposals.mkdir(exist_ok=True)
    target = proposals / f"{_slugify(title)}.md"
    fm_lines = [
        f"title: {_emit_scalar(title)}",
        "status: draft",
        f"kind: {kind}",
        "source_ids:",
        *[f"  - {sid}" for sid in source_ids],
        "trust: derived_review_required",
    ]
    body = (
        "---\n" + "\n".join(fm_lines) + f"\n---\n\n{_PROPOSAL_BANNER}\n\n"
        "## Summary\n\n"
        "State each claim with a visible marker: cited "
        "[source: " + source_ids[0] + "], or [inference], [proposal], "
        "[unknown].\n\n"
        "## Findings\n\n"
        "## Contradictions / Unresolved\n"
    )
    with _safe_create_exclusive(root, target) as fh:
        fh.write(body)
    return target


def lint_proposals(root: Path) -> list[str]:
    """Reduced lint over proposals/ (a lint-blind proposals tree would be a
    second wiki with weaker controls).

    Checks: forbidden chars, full-file imperative scan (no allowed-section
    carve-out in proposals), frontmatter parse, and a hard ban on elevated
    status (reviewed/archived) or trust (reviewed_internal) while under
    proposals/. Citation/link/orphan graphs remain pages-only.
    """
    proposals = root / "proposals"
    violations: list[str] = []
    if proposals.is_symlink():
        # A symlinked proposals/ would make an EXTERNAL directory the
        # containment base for the whole scan — refuse.
        return [f"proposals: directory is a symlink: {proposals}"]
    if proposals.exists() and not proposals.is_dir():
        return [f"proposals: path exists but is not a directory: {proposals}"]
    if not proposals.is_dir():
        return []
    proposals_res = proposals.resolve()
    for p in sorted(proposals.rglob("*.md")):
        name = f"proposals/{p.name}"
        try:
            resolved = p.resolve()
        except (OSError, RuntimeError):  # symlink loop -> violation
            violations.append(f"{name}: unresolvable path (symlink loop?)")
            continue
        if not str(resolved).startswith(str(proposals_res) + os.sep):
            violations.append(f"{name}: escapes proposals/ after resolution")
            continue
        if not resolved.is_file():
            violations.append(f"{name}: does not resolve to a regular file")
            continue
        text, read_violations = _read_page(p, name)
        if text is None:
            violations.extend(read_violations)
            continue
        if _FORBIDDEN_CHARS_RE.search(text):
            violations.append(
                f"{name}: contains zero-width or bidi control characters"
            )
        violations.extend(_scan_imperatives(text, name, "proposal (full file)"))
        fm, _body, fm_violations = _split_frontmatter(text, name)
        violations.extend(fm_violations)
        if fm is not None:
            # Only `draft` belongs under proposals/ — `review`, `reviewed`,
            # and `archived` all imply progress that must happen in pages/
            # via promotion (allowlist, not denylist).
            if fm.get("status") != "draft":
                violations.append(
                    f"{name}: proposals must have status draft, not "
                    f"'{fm.get('status')}'"
                )
            violations.extend(_enum_check(fm, "trust", TRUST_LEVELS, name))
            if fm.get("trust") == "reviewed_internal":
                violations.append(
                    f"{name}: proposals may not claim trust reviewed_internal"
                )
    return violations


