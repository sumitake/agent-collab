def _fold(text: str) -> str:
    """Strip ALL format (Cf) characters, then NFKC-fold, before matching.

    Category-wide Cf stripping (soft hyphen, ZWJ variants, bidi controls,
    anything future) closes the listed-chars-only gap. Confusables and
    homoglyphs remain out of scope: this is a tripwire.
    """
    stripped = "".join(
        c for c in text if unicodedata.category(c) != "Cf"
    )
    return unicodedata.normalize("NFKC", stripped)


def _sanitize_cell(value: object) -> str:
    """Make a value safe for one generated markdown table/log row.

    Newlines/pipes break row structure; link metacharacters would let
    untrusted frontmatter inject live markup into the generated catalog,
    so both classes are stripped, not escaped.
    """
    text = re.sub(r"[\r\n|]+", " ", str(value))
    return re.sub(r"[\[\]()<>`]", "", text).strip()


