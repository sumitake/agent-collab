#!/usr/bin/env python3
"""Deterministic tooling for a project-local knowledge compilation layer.

Ships with the agent-collab plugin's `project-knowledge` skill. The layer is
a `knowledge/` directory inside the USER'S project:

    knowledge/
      sources/registry.yaml   source provenance registry (provenance is DATA,
                              never authorization)
      pages/                  compiled knowledge pages (markdown + frontmatter)
      proposals/              draft skeletons written by `draft` (untrusted;
                              promoted into pages/ only through your own
                              review process)
      index.md / log.md       generated by `index`; never hand-edited

Subcommands:
    init      -- scaffold the knowledge/ directory (idempotent, non-destructive)
    validate  -- schema-validate sources/registry.yaml (read-only)
    lint      -- lint pages/ and proposals/ (read-only)
    index     -- regenerate index.md and append one log.md row (the only
                 overwriting command)
    draft     -- write ONE new proposal skeleton under proposals/ (exclusive
                 create; never touches pages/)
    export    -- serialize selected pages into one explicit, budget-capped
                 bundle file OUTSIDE the knowledge tree

Design constraints:
    - deterministic: sorted traversal, stable output, no network, no cache
      state; every run re-reads the registry and pages fresh
    - stdlib-only (Python 3.10+); page/registry content is DATA, never executed
    - frontmatter and the registry use a RESTRICTED YAML subset parsed by a
      bounded parser (see _parse_restricted_yaml): flat mappings, lists of
      scalars, lists of flat mappings, and block scalars. Anchors, aliases,
      tags, flow mappings, and nested mappings are rejected. All scalars are
      strings; timestamps are validated by grammar, not type resolution.
    - the lint is a tripwire, not a semantic-injection guarantee; pages stay
      untrusted-derived until reviewed regardless of a clean lint pass
"""
