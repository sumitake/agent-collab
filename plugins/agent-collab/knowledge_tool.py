def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Deterministic project-knowledge tooling "
                    "(agent-collab project-knowledge skill)."
    )
    parser.add_argument(
        "command",
        choices=("init", "validate", "lint", "index", "draft", "export"),
    )
    parser.add_argument(
        "--root", type=Path, default=DEFAULT_ROOT,
        help="knowledge layer root (default: ./knowledge)",
    )
    parser.add_argument(
        "--log-timestamp", default=None,
        help="override the log row timestamp (tests only)",
    )
    parser.add_argument("--title", default=None, help="draft: proposal title")
    parser.add_argument(
        "--source-id", action="append", default=[], dest="source_ids",
        help="draft: registered source_id (repeatable, at least one)",
    )
    parser.add_argument(
        "--kind", default="synthesis", help="draft: page kind",
    )
    parser.add_argument(
        "--page", action="append", default=[], dest="pages",
        help="export: page path relative to pages/ (repeatable, explicit)",
    )
    parser.add_argument(
        "--out", type=Path, default=None,
        help="export: output bundle file (must be outside knowledge/)",
    )
    parser.add_argument(
        "--budget-chars", type=int, default=_EXPORT_DEFAULT_BUDGET,
        help="export: cap in code points over the full serialized artifact",
    )
    args = parser.parse_args(argv)

    if args.command == "init":
        return cmd_init(args.root)

    registry, violations = load_registry(args.root)
    if args.command == "validate":
        pass  # registry violations alone decide
    elif args.command == "lint":
        violations = (violations + lint_pages(args.root, registry)
                      + lint_proposals(args.root))
    elif args.command == "draft":
        if violations:
            print("draft: registry invalid; fix before drafting:")
        elif not args.title or not args.source_ids:
            print("draft: --title and at least one --source-id are required")
            return 2
        else:
            target = create_draft(
                args.root, args.title, args.source_ids, args.kind, registry
            )
            print(f"draft: wrote proposal skeleton {target}")
    elif args.command == "export":
        if violations:
            print("export: registry invalid; fix before exporting:")
        elif not args.pages or args.out is None:
            print("export: at least one --page and --out are required")
            return 2
        else:
            out = export_bundle(
                args.root, args.pages, args.out, args.budget_chars,
                registry, args.log_timestamp,
            )
            print(f"export: wrote bundle {out}")
    elif args.command == "index":
        if violations:
            print("index: refusing to generate; registry invalid:")
        else:
            generate_index(args.root, registry, args.log_timestamp)
            print(f"index: wrote {args.root / 'index.md'} (+1 log row)")

    for v in violations:
        print(f"VIOLATION: {v}")
    print(f"{args.command}: {'FAIL' if violations else 'OK'} "
          f"({len(violations)} violation(s))")
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
