def load_registry(root: Path) -> tuple[dict, list[str]]:
    """Parse sources/registry.yaml; returns (registry-mapping, violations)."""
    path = root / "sources" / "registry.yaml"
    violations: list[str] = []
    if not path.is_file():
        return {}, [f"registry missing: {path}"]
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return {}, [f"registry unreadable ({exc.__class__.__name__})"]
    data, err = _parse_restricted_yaml(text, "registry")
    if err:
        return {}, [f"registry unparseable: {err}"]
    if not isinstance(data, dict) or not isinstance(data.get("sources"), list):
        return {}, ["registry must be a mapping with a top-level 'sources' list"]

    seen: dict[str, dict] = {}
    for i, entry in enumerate(data["sources"]):
        where = f"sources[{i}]"
        if not isinstance(entry, dict):
            violations.append(f"{where}: entry must be a mapping")
            continue
        sid = entry.get("source_id")
        if not isinstance(sid, str) or not SOURCE_ID_RE.match(sid):
            violations.append(f"{where}: bad or missing source_id")
            continue
        if sid in seen:
            violations.append(f"{where}: duplicate source_id {sid}")
            continue
        for field in ("kind", "location", "retrieved_at", "trust", "allowed_use"):
            if not entry.get(field):
                violations.append(f"{sid}: missing required field '{field}'")
        violations.extend(_enum_check(entry, "kind", SOURCE_KINDS, sid))
        violations.extend(_enum_check(entry, "trust", TRUST_LEVELS, sid))
        violations.extend(_enum_check(entry, "allowed_use", ALLOWED_USES, sid))
        retrieved = entry.get("retrieved_at")
        if retrieved is not None:
            if not isinstance(retrieved, str):
                violations.append(f"{sid}: retrieved_at must be an ISO-8601 string")
            elif not _valid_iso_timestamp(retrieved):
                violations.append(f"{sid}: retrieved_at is not ISO-8601")
        location = entry.get("location")
        if location is not None and not isinstance(location, str):
            violations.append(f"{sid}: location must be a string scalar")
        reason = entry.get("unhashed_reason")
        if reason is not None and not isinstance(reason, str):
            violations.append(f"{sid}: unhashed_reason must be a string scalar")
        sha = entry.get("content_sha256")
        if sha is None or sha == "":
            if not reason:
                violations.append(
                    f"{sid}: content_sha256 absent and no unhashed_reason given"
                )
        elif not isinstance(sha, str) or not SHA256_RE.match(sha):
            violations.append(f"{sid}: content_sha256 is not 64 lowercase hex chars")
        # Echo-loop guard provenance: `provenance_lineage` is optional
        # (absent = effective "derived", fail-closed by construction) BUT an
        # entry declared `independent` MUST carry a non-empty
        # `upstream_attestation` naming its upstream — otherwise two
        # unattested registrations of the same upstream would each count as
        # a distinct corroboration unit.
        violations.extend(
            _enum_check(entry, "provenance_lineage", PROVENANCE_LINEAGES, sid)
        )
        attestation = entry.get("upstream_attestation")
        if attestation is not None and (
            not isinstance(attestation, str) or not attestation.strip()
        ):
            violations.append(
                f"{sid}: upstream_attestation must be a non-empty string scalar"
            )
        if entry.get("provenance_lineage") == "independent" and not (
            isinstance(attestation, str) and attestation.strip()
        ):
            violations.append(
                f"{sid}: provenance_lineage independent requires a non-empty "
                "upstream_attestation naming its upstream"
            )
        seen[sid] = entry
    return seen, violations


