def export_bundle(root: Path, page_rels: list[str], out: Path, budget: int,
                  registry: dict, stamp: str | None = None) -> Path:
    """Serialize selected pages/ into ONE explicit bundle file.

    Containment: --out must not be under knowledge/ at all (a bundle inside
    the tree becomes a fake page/proposal); selection is explicit argv, only
    from pages/ (proposals denied); refuses lint-failing trees; truncation
    is visible, never silent; budget counts the full serialized artifact.
    """

    root_res = root.resolve()
    out_parent = out.parent.resolve()
    # Component-wise containment: a sibling like <root>-backup must not be
    # refused by a string-prefix comparison.
    if out_parent == root_res or root_res in out_parent.parents:
        raise SystemExit(
            f"export: --out must be outside the knowledge tree: {out}"
        )
    pages_dir = (root / "pages").resolve()
    lint_violations = (lint_pages(root, registry) + lint_proposals(root))
    if lint_violations:
        raise SystemExit(
            "export: refusing to bundle a lint-failing tree "
            f"({len(lint_violations)} violation(s); run lint)"
        )
    sections: list[str] = []
    for rel in page_rels:
        page = (root / "pages" / rel)
        resolved = page.resolve()
        if not str(resolved).startswith(str(pages_dir) + os.sep):
            raise SystemExit(f"export: page outside pages/: {rel}")
        if not resolved.is_file():
            raise SystemExit(f"export: no such page: {rel}")
        text, read_violations = _read_page(page, rel)
        if text is None:
            raise SystemExit("export: " + "; ".join(read_violations))
        fm, body, _v = _split_frontmatter(text, rel)
        fm = fm or {}
        meta = " | ".join(
            f"{k}: {_sanitize_cell(fm.get(k, '-'))}"
            for k in ("title", "status", "trust", "impact", "author",
                      "reviewer", "last_reviewed")
        )
        srcs = fm.get("source_ids")
        src_line = ", ".join(s for s in srcs if isinstance(s, str)) \
            if isinstance(srcs, list) else "-"
        sections.append(
            f"## page: {rel}\n<!-- {meta} -->\n"
            f"<!-- source_ids: {_sanitize_cell(src_line)} -->\n\n"
            f"{body.strip()}\n"
        )
    stamp = stamp or _utc_now()
    header = _bundle_header(page_rels, budget, stamp, True)
    marker = "\n\n...[truncated: budget reached]\n"
    # The banner is a hard floor: truncation may only ever eat page
    # content, never the first-bytes warning.
    if budget < len(header) + len(marker):
        raise SystemExit(
            f"export: budget {budget} smaller than the mandatory banner "
            f"({len(header) + len(marker)} code points)"
        )
    body_text = "\n".join(sections)
    artifact = header + body_text
    if len(artifact) > budget:
        cut = artifact[: budget - len(marker)]
        # If the cut lands inside an HTML comment, close it first so the
        # truncation marker is rendered, not swallowed. Delimiter COUNTING
        # is skewed by a stray visible '-->' in page content; run the
        # char-accurate comment scrubber over the cut and use its end state.
        in_comment = False
        for line in cut.split("\n"):
            _, in_comment = _scrub_comments(line, in_comment)
        if in_comment:
            cut = cut[: len(cut) - 5] + " -->"
        artifact = cut + marker
    with _safe_create_exclusive(out_parent, out_parent / out.name) as fh:
        fh.write(artifact)
    return out


