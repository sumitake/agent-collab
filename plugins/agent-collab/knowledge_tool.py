# --------------------------------------------------------------------------
# restricted YAML subset (bounded, stdlib-only)
# --------------------------------------------------------------------------
#
# Supported shapes (everything the registry and page frontmatter need):
#   key: scalar                    -> str (quotes stripped; "..." via JSON)
#   key: [a, b]                    -> list[str] (inline; [] allowed)
#   key:                           -> followed by an indented block list of
#     - scalar                        scalars, or of flat mappings whose
#     - key: value                    values are scalars, block scalars, or
#       other: value                  one nested block list of scalars
#   key: |  /  key: >              -> block scalar, folded to ONE string
# Rejected outright (violation, never execution or recursion): anchors,
# aliases, tags, flow mappings, nested mappings, tab indentation, and
# duplicate keys. All scalars are returned as STRINGS — no int/bool/date
# resolution, so timestamp policy is enforced by grammar checks, not types.

_UNSUPPORTED_VALUE_RE = re.compile(r"^[&*!{?]")


def _parse_scalar(raw: str) -> tuple[str | None, str | None]:
    """Parse one restricted scalar; returns (value, error)."""
    s = raw.strip()
    if not s:
        return "", None
    if _UNSUPPORTED_VALUE_RE.match(s):
        return None, f"unsupported YAML feature in value {s[:20]!r} (restricted parser)"
    if s.startswith('"'):
        try:
            decoded = json.loads(s)
        except ValueError:
            return None, f"unparseable double-quoted scalar {s[:40]!r}"
        if not isinstance(decoded, str):
            return None, f"double-quoted scalar decoded to {type(decoded).__name__}"
        return decoded, None
    if s.startswith("'"):
        if len(s) >= 2 and s.endswith("'"):
            return s[1:-1].replace("''", "'"), None
        return None, f"unterminated single-quoted scalar {s[:40]!r}"
    # Plain scalar: strip a trailing comment only when whitespace-separated
    # (so URL fragments like page#frag survive).
    s = re.sub(r"\s+#.*$", "", s).strip()
    return s, None


def _parse_inline_list(raw: str) -> tuple[list[str] | None, str | None]:
    inner = raw.strip()[1:-1].strip()
    if not inner:
        return [], None
    items: list[str] = []
    for part in inner.split(","):
        value, err = _parse_scalar(part)
        if err:
            return None, err
        items.append(value)
    return items, None


_KEY_RE = re.compile(r"^([A-Za-z0-9_][A-Za-z0-9_.-]*):(.*)$")


class _Lines:
    """Cursor over raw lines with 1-based numbering for error messages."""

    def __init__(self, text: str) -> None:
        self.lines = text.splitlines()
        self.pos = 0

    def peek(self) -> str | None:
        return self.lines[self.pos] if self.pos < len(self.lines) else None

    def take(self) -> str:
        line = self.lines[self.pos]
        self.pos += 1
        return line


def _indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _collect_block_scalar(cur: _Lines, style: str, parent_indent: int) -> str:
    """Fold a `|` or `>` block scalar into ONE plain string."""
    collected: list[str] = []
    while True:
        line = cur.peek()
        if line is None:
            break
        if line.strip() and _indent_of(line) <= parent_indent:
            break
        cur.take()
        collected.append(line.strip())
    joiner = "\n" if style == "|" else " "
    return joiner.join(c for c in collected if c).strip()


def _parse_mapping_body(
    cur: _Lines, indent: int, owner: str, depth: int
) -> tuple[dict | None, str | None]:
    """Parse `key: value` lines at exactly `indent` into a flat mapping."""
    result: dict[str, object] = {}
    while True:
        line = cur.peek()
        if line is None:
            break
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            cur.take()
            continue
        if "\t" in line[:_indent_of(line)]:
            return None, f"{owner}: tab indentation is not supported"
        line_indent = _indent_of(line)
        if line_indent < indent:
            break
        if line_indent > indent:
            return None, (
                f"{owner}: nested mapping at indent {line_indent} is not "
                f"supported (restricted parser)"
            )
        m = _KEY_RE.match(stripped)
        if not m:
            if stripped.startswith("- "):
                break  # caller's list context resumes
            return None, f"{owner}: unparseable line {stripped[:40]!r}"
        key, rest = m.group(1), m.group(2).strip()
        cur.take()
        if key in result:
            return None, f"{owner}: duplicate key {key!r}"
        if rest in ("|", ">", "|-", ">-", "|+", ">+"):
            result[key] = _collect_block_scalar(cur, rest[0], indent)
            continue
        if rest.startswith("[") and rest.endswith("]"):
            items, err = _parse_inline_list(rest)
            if err:
                return None, f"{owner}: {key}: {err}"
            result[key] = items
            continue
        if rest:
            value, err = _parse_scalar(rest)
            if err:
                return None, f"{owner}: {key}: {err}"
            result[key] = value
            continue
        # Empty value: an indented block list, or genuinely empty.
        nxt = cur.peek()
        while nxt is not None and (not nxt.strip() or nxt.strip().startswith("#")):
            cur.take()
            nxt = cur.peek()
        if nxt is None or _indent_of(nxt) <= indent or not nxt.strip().startswith("- "):
            result[key] = ""
            continue
        if depth >= 2:
            return None, f"{owner}: {key}: list nesting too deep (restricted parser)"
        lst, err = _parse_block_list(cur, _indent_of(nxt), owner, depth + 1)
        if err:
            return None, err
        result[key] = lst
    return result, None


def _parse_block_list(
    cur: _Lines, indent: int, owner: str, depth: int
) -> tuple[list | None, str | None]:
    """Parse `- item` lines at exactly `indent`; items are scalars or flat
    mappings (mappings only at depth 1, i.e. a top-level list of entries)."""
    items: list[object] = []
    while True:
        line = cur.peek()
        if line is None:
            break
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            cur.take()
            continue
        line_indent = _indent_of(line)
        if line_indent != indent or not stripped.startswith("- "):
            if line_indent >= indent and stripped.startswith("- "):
                return None, f"{owner}: misindented list item {stripped[:40]!r}"
            break
        cur.take()
        item_text = stripped[2:].strip()
        m = _KEY_RE.match(item_text)
        if m and depth == 1:
            # List item opens a flat mapping: `- key: value` plus following
            # lines indented past the dash.
            key, rest = m.group(1), m.group(2).strip()
            entry: dict[str, object] = {}
            if rest in ("|", ">", "|-", ">-", "|+", ">+"):
                # Ambiguous continuation indent; require the block scalar on
                # its own continuation line instead.
                return None, (
                    f"{owner}: {key}: block scalar directly on a list-item "
                    f"line is not supported (restricted parser); put the key "
                    f"on a continuation line"
                )
            elif rest.startswith("[") and rest.endswith("]"):
                lst, err = _parse_inline_list(rest)
                if err:
                    return None, f"{owner}: {key}: {err}"
                entry[key] = lst
            else:
                value, err = _parse_scalar(rest)
                if err:
                    return None, f"{owner}: {key}: {err}"
                entry[key] = value
            nxt = cur.peek()
            while nxt is not None and (
                not nxt.strip() or nxt.strip().startswith("#")
            ):
                cur.take()
                nxt = cur.peek()
            if nxt is not None and _indent_of(nxt) > indent and not nxt.strip().startswith("- "):
                rest_map, err = _parse_mapping_body(
                    cur, _indent_of(nxt), owner, depth
                )
                if err:
                    return None, err
                for k, v in rest_map.items():
                    if k in entry:
                        return None, f"{owner}: duplicate key {k!r}"
                    entry[k] = v
            items.append(entry)
            continue
        value, err = _parse_scalar(item_text)
        if err:
            return None, f"{owner}: {err}"
        items.append(value)
    return items, None


def _parse_restricted_yaml(text: str, owner: str) -> tuple[dict | None, str | None]:
    """Parse the restricted subset; returns (mapping, error)."""
    cur = _Lines(text)
    mapping, err = _parse_mapping_body(cur, 0, owner, 0)
    if err:
        return None, err
    remaining = cur.peek()
    if remaining is not None:
        return None, f"{owner}: unparseable trailing line {remaining.strip()[:40]!r}"
    return mapping, None


_SAFE_PLAIN_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 _./:@+-]*$")


def _emit_scalar(value: str) -> str:
    """Emit a scalar that the restricted parser round-trips exactly."""
    if _SAFE_PLAIN_RE.match(value) and "  " not in value and value == value.strip() and "#" not in value:
        return value
    return json.dumps(value, ensure_ascii=False)


