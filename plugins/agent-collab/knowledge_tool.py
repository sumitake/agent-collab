def _enum_check(container: dict, field: str, allowed: set, owner: str) -> list[str]:
    """Type-then-membership check for untrusted enum fields.

    Every value parsed from registry or page frontmatter is
    attacker-influenced data; a non-string value must yield a violation,
    never a TypeError at a set-membership or regex site.
    """
    value = container.get(field)
    if value is None:
        return []  # missing-field reporting is the caller's concern
    if not isinstance(value, str):
        return [f"{owner}: {field} must be a string, got {type(value).__name__}"]
    if value not in allowed:
        return [f"{owner}: {field} not in {sorted(allowed)}"]
    return []


