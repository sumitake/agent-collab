_REGISTRY_SKELETON = """\
# Source provenance registry — parsed by knowledge_tool.py (restricted YAML
# subset: flat mappings, lists, block scalars; no anchors/aliases/tags).
# Each source entry records provenance and constraints; provenance is NOT
# authorization. Example entry:
#
# sources:
#   - source_id: external.example.article.20260101
#     kind: external_research
#     location: https://example.com/article
#     retrieved_at: "2026-01-01T00:00:00Z"
#     content_sha256: ""
#     unhashed_reason: remote source, content hash not captured
#     trust: untrusted_external
#     allowed_use: research_context
sources: []
"""


def cmd_init(root: Path) -> int:
    """Scaffold the knowledge/ layout. Never overwrites existing content."""
    if root.is_symlink():
        raise SystemExit(f"init: refusing symlinked root: {root}")
    if root.exists() and not root.is_dir():
        raise SystemExit(f"init: path exists but is not a directory: {root}")
    created: list[str] = []
    for rel in ("", "sources", "pages", "proposals"):
        target = root / rel if rel else root
        if not target.exists():
            target.mkdir(parents=True)
            created.append(f"{target}/")
        elif not target.is_dir():
            raise SystemExit(f"init: path exists but is not a directory: {target}")
    registry = root / "sources" / "registry.yaml"
    if not registry.exists():
        with _safe_create_exclusive(root, registry) as fh:
            fh.write(_REGISTRY_SKELETON)
        created.append(str(registry))
    if created:
        for item in created:
            print(f"init: created {item}")
    else:
        print("init: already initialized (nothing to do)")
    return 0


