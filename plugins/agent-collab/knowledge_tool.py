def _iter_pages(root: Path) -> tuple[list[Path], list[str]]:
    pages_dir = (root / "pages").resolve()
    violations: list[str] = []
    pages: list[Path] = []
    if not pages_dir.is_dir():
        return [], [f"pages directory missing: {pages_dir}"]
    for p in sorted(pages_dir.rglob("*.md")):
        try:
            resolved = p.resolve()
        except (OSError, RuntimeError):  # symlink loop -> violation
            violations.append(f"{p.name}: unresolvable path (symlink loop?)")
            continue
        if not str(resolved).startswith(str(pages_dir) + os.sep) and resolved != pages_dir:
            violations.append(f"{p.name}: escapes pages/ after symlink resolution")
            continue
        if not resolved.is_file():
            violations.append(
                f"{p.name}: does not resolve to a regular readable file"
            )
            continue
        pages.append(p)
    return pages, violations


def _read_page(page: Path, name: str) -> tuple[str | None, list[str]]:
    """Read a page; any I/O or decode failure is a violation, not a crash."""
    try:
        return page.read_text(encoding="utf-8"), []
    except (OSError, UnicodeDecodeError) as exc:
        return None, [f"{name}: unreadable page ({exc.__class__.__name__})"]


def _split_frontmatter(text: str, name: str) -> tuple[dict | None, str, list[str]]:
    if not text.startswith("---\n"):
        return None, text, [f"{name}: missing YAML frontmatter"]
    end = text.find("\n---", 4)
    if end < 0:
        return None, text, [f"{name}: unterminated frontmatter"]
    raw = text[4:end]
    body = text[end + 4:]
    fm, err = _parse_restricted_yaml(raw, name)
    if err:
        return None, body, [f"{name}: frontmatter unparseable: {err}"]
    if not isinstance(fm, dict):
        return None, body, [f"{name}: frontmatter must be a mapping"]
    return fm, body, []


def _scan_imperatives(text: str, name: str, where: str) -> list[str]:
    folded = _fold(text)
    hits = []
    for pat in IMPERATIVE_PATTERNS:
        m = pat.search(folded)
        if m:
            hits.append(
                f"{name}: imperative/prompt-injection pattern in {where}: "
                f"'{m.group(0)[:60]}'"
            )
    return hits


def _scrub_comments(line: str, in_comment: bool) -> tuple[str, bool]:
    """Return (visible text of line, new comment-state), char-accurate."""
    out: list[str] = []
    i = 0
    while i < len(line):
        if in_comment:
            end = line.find("-->", i)
            if end < 0:
                return "".join(out), True
            in_comment = False
            i = end + 3
        else:
            start = line.find("<!--", i)
            if start < 0:
                out.append(line[i:])
                break
            out.append(line[i:start])
            in_comment = True
            i = start + 4
    return "".join(out), in_comment


class _BodyAnalysis:
    """Single-pass line-classifier over a page body: one state machine shared
    by the claim lint, imperative scan, and allowed-section handling.

    States: fence, html_comment, allowed_section, prose. Visibility for
    claim/marker purposes excludes fenced code and comment content; the
    imperative scan surface excludes ONLY allowed sections (fences and
    comments stay scanned — injection hides there). Allowed sections carve
    out imperatives, never citations.
    """

    def __init__(self, body: str, name: str) -> None:
        self.name = name
        self.violations: list[str] = []
        self.imperative_lines: list[str] = []
        self.claim_runs: list[tuple[str, int]] = []  # (content, markers)
        self.total_claim_chars = 0
        self.total_markers = 0
        # Rendered (non-fence, comment-scrubbed) text: the single surface
        # for citations, trust pinning, and link extraction (fenced or
        # commented examples are neither citations nor links).
        self._visible_lines: list[str] = []
        self._run_content: list[str] = []
        self._run_markers = 0
        self._analyze(body)
        self.visible_text = "\n".join(self._visible_lines)

    def _close_run(self) -> None:
        content = " ".join(s for s in self._run_content if s)
        if content:
            self.claim_runs.append((content, self._run_markers))
        self._run_content = []
        self._run_markers = 0

    def _analyze(self, body: str) -> None:
        in_fence = False
        fence_char = "`"
        fence_len = 3
        in_comment = False
        in_section = False
        section_count = 0
        section_lines_total = 0
        for raw in body.splitlines():
            # Allowed-section markers are themselves HTML comments, so they
            # must be recognized on the RAW line before comment scrubbing —
            # but never from inside a fence or a continuing comment.
            raw_stripped = raw.strip()
            if not in_comment and not in_fence:
                if raw_stripped == ALLOWED_SECTION_START:
                    if in_section:
                        self.violations.append(
                            f"{self.name}: nested allowed-directives section"
                        )
                    in_section = True
                    section_count += 1
                    if section_count > ALLOWED_SECTION_MAX_COUNT:
                        self.violations.append(
                            f"{self.name}: more than {ALLOWED_SECTION_MAX_COUNT} "
                            f"allowed-directives sections"
                        )
                    continue
                if raw_stripped == ALLOWED_SECTION_END:
                    if not in_section:
                        self.violations.append(
                            f"{self.name}: allowed-directives end without start"
                        )
                    in_section = False
                    continue

            visible, new_comment = _scrub_comments(raw, in_comment)
            in_comment_line = in_comment or new_comment
            in_comment = new_comment
            stripped = visible.strip()

            # Fence state: a fence line is a run of 3+ identical backticks
            # or tildes indented at most 3 spaces (4+ spaces is indented
            # code, not a fence), outside comments. The opening delimiter's
            # char and length are recorded; only a run of the SAME char at
            # least as long, with nothing else on the line, closes it.
            fence_eligible = bool(re.match(r"^ {0,3}\S", visible))
            if not in_comment_line and not in_fence and fence_eligible:
                m = re.match(r"^(`{3,}|~{3,})", stripped)
                if m:
                    in_fence = True
                    fence_char = m.group(1)[0]
                    fence_len = len(m.group(1))
                    self._close_run()
                    self.imperative_lines.append(raw)
                    continue
            elif not in_comment_line and in_fence:
                if fence_eligible and re.fullmatch(
                    rf"{re.escape(fence_char)}{{{fence_len},}}\s*", stripped
                ):
                    in_fence = False
                    self._close_run()
                    self.imperative_lines.append(raw)
                    continue

            if in_section:
                section_lines_total += 1
                if section_lines_total == ALLOWED_SECTION_MAX_LINES + 1:
                    self.violations.append(
                        f"{self.name}: allowed-directives content exceeds "
                        f"{ALLOWED_SECTION_MAX_LINES} lines per page"
                    )
            else:
                # Everything outside allowed sections is imperative-scanned,
                # including fence and comment content (raw line, deliberately).
                self.imperative_lines.append(raw)

            if in_fence:
                self._close_run()
                continue

            self._visible_lines.append(visible)

            if not stripped:
                self._close_run()
                continue

            # Markers count only when visible (comments already scrubbed).
            line_markers = len(CLAIM_MARKER_RE.findall(visible))
            self.total_markers += line_markers

            if stripped.startswith("#"):
                # Headings are labels, but a substantive heading is still a
                # claim: at >= _CLAIM_MIN_CHARS it needs a marker and counts
                # toward page density.
                heading_text = stripped.lstrip("#").strip()
                if len(heading_text) >= _CLAIM_MIN_CHARS:
                    self.total_claim_chars += len(heading_text)
                    if not CLAIM_MARKER_RE.search(visible):
                        self.violations.append(
                            f"{self.name}: claim-length heading without "
                            f"marker: '{heading_text[:60]}...'"
                        )
                self._close_run()
                continue
            if re.fullmatch(r"\|[\s:|-]+\|?", stripped):
                continue  # table separator row
            content = re.sub(r"^[>|\s]+", "", stripped).strip("| ")
            if content:
                self._run_content.append(content)
                self._run_markers += line_markers
                self.total_claim_chars += len(content)
        self._close_run()
        if in_comment:
            self.violations.append(f"{self.name}: unterminated HTML comment")
        if in_fence:
            self.violations.append(f"{self.name}: unterminated code fence")
        if in_section:
            self.violations.append(
                f"{self.name}: unterminated allowed-directives section"
            )


def _lint_claims(analysis: "_BodyAnalysis", name: str,
                 registry: dict) -> list[str]:
    """Citation rules over the analyzed body.

    Local rule: every claim run of >= _CLAIM_MIN_CHARS visible chars needs a
    marker INSIDE that run (a marker in a fence, comment, or another run
    cannot vouch for it). Global rule: total visible claim content needs one
    marker per _CLAIM_CHARS_PER_MARKER chars, so sub-threshold fragmentation
    cannot aggregate uncited meaning.
    """
    violations: list[str] = []
    for content, markers in analysis.claim_runs:
        if len(content) >= _CLAIM_MIN_CHARS and markers == 0:
            violations.append(
                f"{name}: uncited claim run (no visible marker inside it): "
                f"'{content[:60]}...'"
            )
    if analysis.total_claim_chars >= _CLAIM_MIN_CHARS:
        required = 1 + (analysis.total_claim_chars - 1) // _CLAIM_CHARS_PER_MARKER
        if analysis.total_markers < required:
            violations.append(
                f"{name}: under-cited page ({analysis.total_markers} visible "
                f"marker(s), {required} required for "
                f"{analysis.total_claim_chars} visible claim chars)"
            )
    # Only VISIBLE citations are claims; a fenced example citing a ghost id
    # is documentation, not a citation.
    for sid in _CITED_SOURCE_RE.findall(analysis.visible_text):
        if sid not in registry:
            violations.append(
                f"{name}: claim cites unregistered source_id '{sid}'"
            )
    return violations


def _iter_fm_strings(value: object, path: str = "frontmatter"):
    """Yield (path, string) for every string nested anywhere in frontmatter.

    The restricted parser cannot produce cycles (no anchors/aliases), so a
    bounded walk suffices.
    """
    if isinstance(value, str):
        yield path, value
        return
    if isinstance(value, dict):
        for k, v in sorted(value.items(), key=lambda kv: str(kv[0])):
            if isinstance(k, str):
                yield f"{path} key", k
            yield from _iter_fm_strings(v, f"{path}.{k}")
    elif isinstance(value, (list, tuple)):
        for i, v in enumerate(value):
            yield from _iter_fm_strings(v, f"{path}[{i}]")


def _lint_review_fields(fm: dict, name: str) -> list[str]:
    """Review-consistency tripwires (schema checks, NOT a review).

    Rules: status reviewed requires reviewer + ISO last_reviewed; trust
    reviewed_internal requires status reviewed (trust<->status coupling);
    impact high + status reviewed additionally requires author, and
    reviewer must differ from author under fold+casefold equality
    (homoglyph self-review is a documented residual — your review process
    owns it). status archived freezes fields: no additional gates.
    """
    violations: list[str] = []
    status = fm.get("status")
    if fm.get("trust") == "reviewed_internal" and status != "reviewed":
        violations.append(
            f"{name}: trust reviewed_internal requires status reviewed"
        )
    if status != "reviewed":
        return violations
    reviewer = fm.get("reviewer")
    if not isinstance(reviewer, str) or not reviewer.strip():
        violations.append(f"{name}: status reviewed requires a reviewer string")
        reviewer = None
    last = fm.get("last_reviewed")
    if isinstance(last, str) and last.strip():
        if not _valid_iso_timestamp(last):
            violations.append(f"{name}: last_reviewed is not ISO-8601")
    else:
        violations.append(
            f"{name}: status reviewed requires an ISO-8601 last_reviewed"
        )
    if fm.get("impact") == "high":
        author = fm.get("author")
        if not isinstance(author, str) or not author.strip():
            violations.append(
                f"{name}: impact high + reviewed requires an author string"
            )
        elif reviewer is not None and (
            _fold(reviewer).casefold().strip()
            == _fold(author).casefold().strip()
        ):
            violations.append(
                f"{name}: high-impact page reviewed by its own author "
                f"('{author}') — distinct reviewer required"
            )
    return violations


def lint_pages(root: Path, registry: dict) -> list[str]:
    pages, violations = _iter_pages(root)
    _pages_dir = (root / "pages").resolve()
    page_names = {p.resolve().relative_to(_pages_dir).as_posix() for p in pages}
    referenced: set[str] = set()

    for page in pages:
        name = page.name
        text, read_violations = _read_page(page, name)
        if text is None:
            violations.extend(read_violations)
            continue

        if _FORBIDDEN_CHARS_RE.search(text):
            violations.append(
                f"{name}: contains zero-width or bidi control characters"
            )

        fm, body, fm_violations = _split_frontmatter(text, name)
        violations.extend(fm_violations)
        analysis = _BodyAnalysis(body, name)

        if fm is not None:
            for field in ("title", "status", "kind", "source_ids", "trust"):
                if not fm.get(field):
                    violations.append(f"{name}: frontmatter missing '{field}'")
            violations.extend(_enum_check(fm, "status", PAGE_STATUSES, name))
            violations.extend(_enum_check(fm, "kind", PAGE_KINDS, name))
            violations.extend(_enum_check(fm, "trust", TRUST_LEVELS, name))
            violations.extend(_enum_check(fm, "impact", PAGE_IMPACTS, name))
            violations.extend(_lint_review_fields(fm, name))

            source_ids = fm.get("source_ids") or []
            if not isinstance(source_ids, list):
                violations.append(f"{name}: source_ids must be a list")
                source_ids = []
            cited: set[str] = set()
            for sid in source_ids:
                if not isinstance(sid, str):
                    violations.append(
                        f"{name}: source_ids entry is not a string: {sid!r}"
                    )
                elif sid not in registry:
                    violations.append(f"{name}: cites unregistered source_id '{sid}'")
                else:
                    cited.add(sid)
            # VISIBLE body [source:] citations count toward trust too —
            # declaring only trusted sources in frontmatter while citing a
            # weaker one inline must not evade the pin; fenced or commented
            # example citations do NOT count.
            cited.update(
                s for s in _CITED_SOURCE_RE.findall(analysis.visible_text)
                if s in registry
            )
            # Trust lattice: page trust may not exceed the ceiling of its
            # weakest cited source. Frontmatter is data, not authorization.
            page_trust = fm.get("trust")
            if cited and isinstance(page_trust, str) and page_trust in PAGE_TRUST_RANK:
                ceilings = [
                    SOURCE_TRUST_CEILING.get(str(registry[s].get("trust")), "derived_review_required")
                    for s in cited
                ]
                weakest = min(ceilings, key=lambda c: PAGE_TRUST_RANK[c])
                if PAGE_TRUST_RANK[page_trust] > PAGE_TRUST_RANK[weakest]:
                    violations.append(
                        f"{name}: trust '{page_trust}' exceeds ceiling "
                        f"'{weakest}' imposed by its weakest cited source"
                    )
            # Every string nested anywhere in frontmatter shares the
            # imperative scan surface (not just top-level values).
            for where, value in _iter_fm_strings(fm):
                violations.extend(_scan_imperatives(value, name, where))

        violations.extend(analysis.violations)
        violations.extend(
            _scan_imperatives("\n".join(analysis.imperative_lines), name, "body")
        )
        violations.extend(_lint_claims(analysis, name, registry))

        # Links are extracted from the VISIBLE surface only: fenced markdown
        # examples and commented-out links are not rendered links.
        for target, contributes_inbound in _extract_link_targets(
            analysis.visible_text
        ):
            # Any URI scheme or protocol-relative reference is external and
            # gets no filesystem checks; '#' is a same-page anchor.
            if target.startswith(("#", "//")) or _URI_SCHEME_RE.match(target):
                continue
            # Decode, then contain: percent-encoding must not smuggle
            # traversal past the realpath containment check. Parent-relative
            # links between nested sibling dirs are legitimate; containment,
            # not lexical '..', decides.
            fs_target = unquote(re.split(r"[#?]", target, maxsplit=1)[0])
            if not fs_target:
                continue
            resolved = (page.parent / fs_target).resolve()
            pages_dir = (root / "pages").resolve()
            if not str(resolved).startswith(str(pages_dir) + os.sep):
                violations.append(f"{name}: link escapes pages/: {target}")
            elif not resolved.exists():
                violations.append(f"{name}: broken internal link: {target}")
            elif resolved != page.resolve() and contributes_inbound:
                # Self-links do not satisfy the inbound-reference
                # requirement, and unused reference definitions
                # validity-check but do not vouch for their target.
                referenced.add(resolved.relative_to(pages_dir).as_posix())

    # Orphans: only meaningful once more than one page exists.
    if len(pages) > 1:
        for rel in sorted(page_names - referenced):
            violations.append(f"{rel}: orphan page (no inbound internal link)")
    return violations


