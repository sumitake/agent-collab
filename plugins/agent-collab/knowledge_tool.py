# Reference-style definitions: `[ref]: target "optional title"` — their
# targets are link-linted too, so switching Markdown syntax cannot bypass
# the broken-internal-link check.
_MD_REF_DEF_RE = re.compile(
    r"""^\s{0,3}\[([^\]^\n]+)\]:\s*<?([^\s>]+)>?""", re.MULTILINE
)
# Reference USES: full `[text][label]` and collapsed `[label][]` count as
# uses; bare shortcut `[label]` does NOT (indistinguishable from claim
# markers and plain brackets). Labels match case-insensitively after
# whitespace-normalization, per CommonMark.
_MD_REF_USE_RE = re.compile(r"\]\[([^\]]+)\]|\[([^\]]+)\]\[\]")


def _norm_label(label: str) -> str:
    return re.sub(r"\s+", " ", label.strip()).casefold()


# Inline code spans delimit with EQUAL-length backtick runs (CommonMark).
_CODE_SPAN_RE = re.compile(r"(?<!`)(`+)(?!`)([^\n]+?)(?<!`)\1(?!`)")
# Any RFC-3986 scheme (ftp:, mailto:, data:, ...) or a protocol-relative
# reference is external; filesystem checks apply only to local paths.
_URI_SCHEME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")


def _find_inline_link_targets(text: str) -> list[str]:
    """Extract inline-link destinations with balanced/escaped parentheses.

    A regex terminating at the first ')' truncates `[x](foo(1).md)`; this
    scanner tracks paren depth, honors backslash escapes, `<...>`
    destinations, and stops the destination at depth-1 whitespace (the
    optional title).
    """
    targets: list[str] = []
    i = 0
    while True:
        j = text.find("](", i)
        if j < 0:
            return targets
        k = j + 2
        while k < len(text) and text[k] in " \t":
            k += 1
        if k < len(text) and text[k] == "<":
            end = text.find(">", k + 1)
            if end < 0:
                i = j + 2
                continue
            targets.append(text[k + 1:end])
            i = end + 1
            continue
        depth = 1
        dest: list[str] = []
        while k < len(text):
            c = text[k]
            if c == "\\" and k + 1 < len(text):
                dest.append(text[k + 1])
                k += 2
                continue
            if c == "(":
                depth += 1
                dest.append(c)
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
                dest.append(c)
            elif c in " \t" and depth == 1:
                # Optional title begins; skip to the matching close paren.
                while k < len(text):
                    if text[k] == "(":
                        depth += 1
                    elif text[k] == ")":
                        depth -= 1
                        if depth == 0:
                            break
                    k += 1
                break
            elif c == "\n":
                break  # destinations do not span lines
            else:
                dest.append(c)
            k += 1
        if dest:
            targets.append("".join(dest))
        i = k + 1


def _extract_link_targets(body: str) -> list[tuple[str, bool]]:
    """Return (target, contributes_inbound) pairs from rendered text.

    Inline links always contribute an inbound reference to their target.
    Reference DEFINITIONS are always validity-checked (broken targets flag
    regardless), but contribute inbound only when their label is actually
    used (an unused `[unused]: b.md` must not cure b.md's orphan status).
    Inline CODE SPANS are literal text, not rendered links or reference
    uses, and are removed from this surface first.
    """
    rendered = _CODE_SPAN_RE.sub(" ", body)
    used = {
        _norm_label(a or b) for a, b in _MD_REF_USE_RE.findall(rendered)
    }
    pairs: list[tuple[str, bool]] = [
        (t, True) for t in _find_inline_link_targets(rendered)
    ]
    for label, target in _MD_REF_DEF_RE.findall(rendered):
        pairs.append((target, _norm_label(label) in used))
    return pairs


